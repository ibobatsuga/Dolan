const todayBase = new Date();
const isoAtHour = (dayOffset: number, hour: number, minute = 0) => {
  const d = new Date(todayBase);
  d.setDate(d.getDate() + dayOffset);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

